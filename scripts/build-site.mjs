#!/usr/bin/env node
/**
 * Builds the static content pages, the 404 page and sitemap.xml into public/,
 * and keeps the generated <head>/footer blocks of public/index.html in sync.
 *
 *   npm run site:build          write the files; bump <lastmod> for pages whose
 *                               own content changed (site/lastmod.json)
 *   npm run site:build -- --check
 *                               write nothing; exit 1 if anything is stale
 *                               (tests/site/site.test.js runs the same check)
 *
 * <lastmod> follows Google's guidance: it moves only when a page's own content
 * changes (a hash of its main content), never on every deploy.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHROME, OG_IMAGE, ORIGIN, PUBLIC_DIR, ROOT } from '../site/config.mjs';
import { abs, esc, footer, headTags, homeAbout, jsonLdFor, mainContent, renderPage } from '../site/layout.mjs';
import en from '../site/pages/en.mjs';
import es from '../site/pages/es.mjs';

const LASTMOD_FILE = resolve(ROOT, 'site/lastmod.json');
const MARK = {
  head: ['<!-- seo:start (generated by scripts/build-site.mjs) -->', '<!-- seo:end -->'],
  footer: ['<!-- footer:start (generated by scripts/build-site.mjs) -->', '<!-- footer:end -->'],
  about: ['<!-- about:start (generated by scripts/build-site.mjs) -->', '<!-- about:end -->'],
};

export const pages = [...en, ...es];

/** public/ file that serves a page path. */
export function fileFor(path) {
  if (path.endsWith('/')) return `${path.slice(1)}index.html`;
  return `${path.slice(1)}.html`;
}

function appGraph(page) {
  return {
    ...page,
    app: {
      '@type': 'WebApplication',
      '@id': `${ORIGIN}/#app`,
      name: 'Pastty',
      url: `${ORIGIN}/`,
      description: page.description,
      applicationCategory: 'UtilitiesApplication',
      operatingSystem: 'Any',
      browserRequirements: 'A current web browser with JavaScript enabled',
      image: abs(OG_IMAGE.path),
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD' },
      isAccessibleForFree: true,
      inLanguage: 'en',
    },
  };
}

function replaceBetween(source, [start, end], content, file) {
  const a = source.indexOf(start);
  const b = source.indexOf(end);
  if (a < 0 || b < a) throw new Error(`${file}: missing ${start} … ${end}`);
  return source.slice(0, a + start.length) + `\n  ${content}\n  ` + source.slice(b);
}

// The head and footer are shared chrome; the about block is the page's own
// content, so it stays in the hash that drives <lastmod>.
function stripChrome(source) {
  let out = source;
  for (const [start, end] of [MARK.head, MARK.footer]) {
    const a = out.indexOf(start);
    const b = out.indexOf(end);
    if (a >= 0 && b > a) out = out.slice(0, a) + out.slice(b + end.length);
  }
  return out;
}

const hash = (text) => createHash('sha256').update(text).digest('hex').slice(0, 16);

function notFoundPage() {
  const t = CHROME.en;
  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0, viewport-fit=cover">
  <meta name="robots" content="noindex">
  <meta name="theme-color" content="#f7f2ea">
  <title>Page not found · Pastty</title>
  <link rel="icon" type="image/svg+xml" href="/icon.svg">
  <link rel="stylesheet" href="/css/style.css">
  <link rel="stylesheet" href="/css/pages.css">
</head>
<body class="content-page">
  <header class="site-header">
    <a class="brand" href="/" aria-label="Pastty"><img src="/icon.svg" alt="" width="48" height="48"><span>Pastty<span class="brand-period">.</span></span></a>
  </header>
  <main class="page-main page-404" id="content">
    <h1>This strand leads nowhere<span class="brand-period">.</span></h1>
    <p class="page-lede">Error 404: the address may be mistyped, or the page has moved. Your devices are still one code away.</p>
    <div class="page-cta"><a class="btn-primary page-btn" href="/">${esc(t.open)}</a><a class="page-link" href="/faq">FAQ</a><a class="page-link" href="/how-it-works">How it works</a></div>
    <p class="page-404-es" lang="es">¿Buscabas la versión en español? <a href="/es/">Ir al inicio en español</a>.</p>
  </main>
</body>
</html>
`;
}

function sitemap(entries) {
  const urls = entries.map(({ page, lastmod }) => {
    const alts = pages.filter((p) => p.id === page.id);
    const links = [...alts.map((p) => [p.lang, p.path]), ['x-default', alts.find((p) => p.lang === 'en').path]]
      .map(([hl, p]) => `\n    <xhtml:link rel="alternate" hreflang="${hl}" href="${abs(p)}"/>`).join('');
    return `  <url>\n    <loc>${abs(page.path)}</loc>\n    <lastmod>${lastmod}</lastmod>${links}\n  </url>`;
  });
  return `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">
${urls.join('\n')}
</urlset>
`;
}

/**
 * Computes every generated file. With `today`, pages whose content hash moved
 * get that date; without it the recorded dates are kept and staleness is
 * reported instead.
 */
export function buildSite({ today } = {}) {
  const recorded = existsSync(LASTMOD_FILE) ? JSON.parse(readFileSync(LASTMOD_FILE, 'utf8')) : {};
  const registry = {};
  const stale = [];
  const files = new Map();
  const entries = [];

  for (const id of new Set(pages.map((p) => p.id))) {
    for (const lang of ['en', 'es']) {
      if (!pages.some((p) => p.id === id && p.lang === lang)) throw new Error(`page "${id}" has no ${lang} version`);
    }
  }

  for (const raw of pages) {
    const page = raw.id === 'home' ? appGraph(raw) : raw;
    const file = fileFor(page.path);
    let output;
    let contentHash;
    if (page.external) {
      const source = readFileSync(resolve(PUBLIC_DIR, page.external), 'utf8');
      const alternates = Object.fromEntries(pages.filter((p) => p.id === page.id).map((p) => [p.lang, p.path]));
      const head = headTags({ lang: page.lang, path: page.path, title: page.title, description: page.description, alternates, ogAlt: page.ogAlt, jsonLd: jsonLdFor(page) });
      output = replaceBetween(source, MARK.head, head, page.external);
      output = replaceBetween(output, MARK.footer, footer(page.lang, pages), page.external);
      output = replaceBetween(output, MARK.about, homeAbout(page, pages), page.external);
      contentHash = hash(stripChrome(output));
    } else {
      output = renderPage(page, pages);
      contentHash = hash(mainContent(page, pages));
    }
    files.set(file, output);

    const prev = recorded[page.path];
    let lastmod = prev?.lastmod;
    if (!prev || prev.hash !== contentHash) {
      if (today) lastmod = today;
      else stale.push(page.path);
    }
    registry[page.path] = { hash: contentHash, lastmod: lastmod ?? '1970-01-01' };
    entries.push({ page, lastmod: registry[page.path].lastmod });
  }

  files.set('404.html', notFoundPage());
  files.set('sitemap.xml', sitemap(entries));
  return { files, registry, stale };
}

function main() {
  const check = process.argv.includes('--check');
  const today = check ? undefined : new Date().toISOString().slice(0, 10);
  const { files, registry, stale } = buildSite({ today });
  const changed = [...files].filter(([file, content]) => {
    const path = resolve(PUBLIC_DIR, file);
    return !existsSync(path) || readFileSync(path, 'utf8') !== content;
  });

  if (check) {
    const problems = [...stale.map((p) => `lastmod is stale for ${p}`), ...changed.map(([f]) => `public/${f} is out of date`)];
    if (problems.length) {
      console.error(`${problems.join('\n')}\nRun: npm run site:build`);
      process.exit(1);
    }
    console.log(`Site is up to date (${files.size} files).`);
    return;
  }

  for (const [file, content] of changed) {
    const path = resolve(PUBLIC_DIR, file);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
  writeFileSync(LASTMOD_FILE, `${JSON.stringify(registry, null, 2)}\n`);
  console.log(`Wrote ${changed.length} of ${files.size} files.`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
